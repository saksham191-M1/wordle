/** Check if a 5-letter word is an allowed guess */
export function isValidWord(word: string): boolean {
  if (!word || word.length !== 5) return false;
  return ALL_VALID_SET.has(word.toUpperCase());
}

/**
 * Returns the daily target word deterministically for a given calendar day.
 * Epoch: Jan 1, 2024
 */
export function getDailyWordAndIndex(): { word: string; dayIndex: number; dateString: string } {
  const epoch = new Date(2024, 0, 1).getTime();
  const now = new Date();
  // Use local calendar date to avoid midnight timezone jumps
  const localDate = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const diffDays = Math.floor((localDate.getTime() - epoch) / (1000 * 60 * 60 * 24));
  const dayIndex = Math.max(1, diffDays);
  
  // Deterministic index in TARGET_WORDS
  const wordIndex = dayIndex % TARGET_WORDS.length;
  const word = TARGET_WORDS[wordIndex];

  const dateString = localDate.toLocaleDateString(undefined, {
    month: 'short',
    day: 'numeric',
    year: 'numeric'
  });

  return { word, dayIndex, dateString };
}

