// Fast lookup Set of all valid guess words (TARGET_WORDS + ADDITIONAL_GUESSES)
const ALL_VALID_SET = new Set<string>();
for (const word of TARGET_WORDS) {
  ALL_VALID_SET.add(word);
}
for (const word of ADDITIONAL_GUESSES) {
  ALL_VALID_SET.add(word);
}

/** Check if a word is a valid 5-letter guess */
export function isValidWord(word: string): boolean {
  if (!word || typeof word !== 'string' || word.length !== 5) return false;
  return ALL_VALID_SET.has(word.toUpperCase());
}

/**
 * Returns UTC date key string 'YYYY-MM-DD' for any given Date object.
 */
export function getUtcDateKey(date: Date = new Date()): string {
  const y = date.getUTCFullYear();
  const m = String(date.getUTCMonth() + 1).padStart(2, '0');
  const d = String(date.getUTCDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Returns the daily target word deterministically for a given calendar day in UTC.
 * Global epoch: Jan 1, 2024 00:00:00 UTC.
 * All players globally share the identical word for each UTC date.
 */
export function getDailyWordAndIndex(date: Date = new Date()): {
  word: string;
  dayIndex: number;
  dateString: string;
  dateKey: string;
} {
  const epoch = Date.UTC(2024, 0, 1);
  const currentUtcMidnight = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate());
  const diffDays = Math.floor((currentUtcMidnight - epoch) / (1000 * 60 * 60 * 24));
  const dayIndex = Math.max(1, diffDays);

  const wordIndex = dayIndex % TARGET_WORDS.length;
  const word = TARGET_WORDS[wordIndex];

  const dateKey = getUtcDateKey(date);
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const dateString = `${months[date.getUTCMonth()]} ${date.getUTCDate()}, ${date.getUTCFullYear()}`;

  return { word, dayIndex, dateString, dateKey };
}

/** Returns a random target word for practice mode, optionally excluding recent words */
export function getRandomWord(excludeList: string[] = []): string {
  const excludeSet = new Set(excludeList.map(w => w.toUpperCase()));
  const pool = TARGET_WORDS.filter(w => !excludeSet.has(w));
  const listToUse = pool.length > 50 ? pool : TARGET_WORDS;
  const randomIndex = Math.floor(Math.random() * listToUse.length);
  return listToUse[randomIndex];
}
